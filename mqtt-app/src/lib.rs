//! # mqtt-app 共通ライブラリ
//!
//! このファイルは「ライブラリクレート」のルートです。C++でいうと、静的/共有ライブラリの
//! ヘッダ群をまとめた1つの入り口、というイメージに近いです。
//!
//! このプロジェクトは実行ファイルを2本作ります（`src/bin/mqtt-server.rs`と
//! `src/bin/mqtt-client.rs`）。CMakeで例えると、1つの`CMakeLists.txt`から
//! `add_executable(mqtt-server ...)`と`add_executable(mqtt-client ...)`を
//! 2回呼んで、共通の`.cpp`/`.h`群（＝このlib.rs以下のモジュール群）を
//! 両方からリンクしている、というのに近い構成です。
//!
//! 以前は`mqtt-server`と`mqtt-client`を完全に別プロジェクト（別Cargo.toml）にしていて、
//! メッセージ定義など共通のコードを2箇所にコピーして持っていました。このプロジェクトは
//! その反省を踏まえて、共通コードを1箇所（このライブラリ）にまとめ直したものです。
//! （元の2プロジェクトは`mqtt-server/`・`mqtt-client/`ディレクトリにそのまま残してあります）
//!
//! ## モジュール一覧（＝ファイル一覧）
//!
//! - [`messages`] — MQTT上でやり取りするメッセージの形（JSON）。いわば通信プロトコルの定義書
//! - [`seq`] — メッセージの抜け（欠落）を検知するための連番の仕組み
//! - [`broker`] — MQTTブローカー（サーバー本体）の起動処理。`mqtt-server`だけが使う
//! - [`controller`] — 「パソコン役」の指示出しロジック（チャット・`/send`・`/job`）。`mqtt-server`だけが使う
//! - [`file_transfer`] — 「マイコン役」の、生TCPでのファイル受信ロジック。`mqtt-client`だけが使う
//! - [`device`] — 「マイコン役」の、OFFER/JOB受信時の処理。`mqtt-client`だけが使う
//!
//! ## Rustが初めての方（C++経験者向け）の予備知識
//!
//! このプロジェクトのコードを読むうえで出てくる、C++には無い（または形が違う）Rust特有の
//! 概念を先にまとめておきます。各ファイルのコメントでも、必要に応じてここを指し示します。
//!
//! ### 1. `mod`とファイル分割 ≒ C++の名前空間＋ヘッダ/ソース分割
//!
//! Rustには`.h`（ヘッダ）と`.cpp`（実装）の区別がありません。`mod messages;`と書くと
//! `messages.rs`というファイル1つが、それだけで宣言と実装を両方含む「モジュール」になります。
//! C++の名前空間と違い、中身は**デフォルトで非公開（private）**で、`pub`を付けた項目だけが
//! 外（他のモジュールや、このライブラリを使う`mqtt-server.rs`/`mqtt-client.rs`）から見えます。
//!
//! ### 2. 所有権（ownership）と借用（borrow）≒ C++のスマートポインタ＋参照だが、コンパイラが強制
//!
//! C++では`std::unique_ptr`や`std::shared_ptr`、参照(`&`)、生ポインタを状況に応じて使い分けますが、
//! 「今どの変数がこのメモリの持ち主か」「誰かが使っている間に消していないか」は基本的に**人間が
//! 気をつける**必要があります（ダングリングポインタ、二重解放、データ競合はC++の典型的なバグです）。
//!
//! Rustでは、値には常に「所有者」が1人だけいて、所有者が使われなくなる（スコープを抜ける）と
//! 自動的に解放されます（これ自体はC++のRAII/デストラクタと同じ考え方です）。
//! 違うのは、**値を他の変数に代入すると「所有権が移動（move）」し、元の変数はもう使えなくなる**
//! （使おうとするとコンパイルエラー）という点と、「借用」（`&T`は読み取り専用の参照、
//! `&mut T`は書き込み可能な参照）には**「書き込み参照は同時に1つまで、読み取り参照はいくつでも
//! いいが書き込み参照と同時には持てない」というルールをコンパイラが機械的にチェックする**点です。
//! これにより、C++でありがちな「あるスレッドが書き込み中に、別スレッドが読んでしまう」ような
//! データ競合が、実行前（コンパイル時）に検出されます。
//!
//! ### 3. `Option<T>` ≒ C++17の`std::optional<T>`
//!
//! 「値があるかもしれないし無いかもしれない」を表す型です。C++でよくあるヌルポインタでの
//! 表現（`nullptr`チェック忘れ→クラッシュ）の代わりに、Rustでは`Option<T>`の中身を
//! 取り出そうとすると、コンパイラが「Noneだった場合の処理も書け」と強制してきます。
//!
//! ### 4. `Result<T, E>` ≒ 例外の代わりに戻り値でエラーを表す（Goのエラー処理に近い）
//!
//! C++の例外(`throw`/`catch`)のように「投げて、離れた場所でキャッチする」のではなく、
//! 「失敗するかもしれない関数は`Result<成功時の型, 失敗時の型>`を返す」という形で、
//! 呼び出し側に**必ず**成功/失敗どちらもその場で処理させます。`?`という記号は、
//! 「エラーだったら即座にreturnする」という定型処理を1文字で書けるようにした糖衣構文です。
//!
//! ### 5. トレイト（trait）≒ C++の抽象基底クラス（純粋仮想関数）に近いが、後から追加できる
//!
//! `trait`は「この型はこういう操作ができる」という約束事の集まりで、C++の`virtual`関数だけの
//! 抽象クラスに似ています。ただしC++と違い、**自分が定義していない型（他のライブラリの型）にも
//! 後からtraitを実装できます**。また`#[derive(Serialize, Deserialize)]`のように書くだけで、
//! 「この構造体をJSONに変換する処理」を自動生成してくれる仕組み（マクロ）もよく使われます。
//! これはC++のリフレクションが無い代わりの定番パターンです。
//!
//! ### 6. `Arc<Mutex<T>>` ≒ C++の`std::shared_ptr<T>` + `std::mutex`の合わせ技
//!
//! `Arc`（Atomically Reference Counted）は`std::shared_ptr`と同じ「参照カウント方式の
//! 共有ポインタ」です。`Mutex`はC++の`std::mutex`と同じ排他ロックですが、Rustの`Mutex<T>`は
//! **中身のデータそのものを抱え込んでいて、ロックを取らないと中身に一切触れない**ように
//! コンパイラが強制する点がC++と違います（C++では`mutex`と保護対象のデータが別変数なので、
//! ロックを取り忘れて直接データに触ってしまう、というバグが起こり得ます。Rustではそもそも
//! 触る手段が無いので、そのバグ自体が起こりません）。
//!
//! ### 7. スレッドとクロージャの`move`
//!
//! `thread::spawn(move || { ... })`はC++の`std::thread(lambda)`に相当しますが、`move`と
//! 書くことで「このクロージャ（ラムダ式）が使う変数の所有権を、新しいスレッドに完全に
//! 渡す」ことを明示します。渡したあとは元のスレッドではその変数を使えなくなるので、
//! 「2つのスレッドが同じ変数を同時にいじってしまう」というバグがコンパイル時に防げます。
//!
//! ### 8. Cargo ≒ CMake + vcpkg/Conan（パッケージ管理）
//!
//! `Cargo.toml`はCMakeの`CMakeLists.txt`と、外部ライブラリの依存関係リスト（vcpkgの
//! `vcpkg.json`やConanの`conanfile.txt`に相当）を兼ねたファイルです。`Cargo.lock`は
//! 実際に使われた依存ライブラリの正確なバージョンを記録したロックファイル（vcpkgでいう
//! `vcpkg.lock`に近いもの）で、Gitで管理してチーム全員が同じバージョンを使うようにします。

